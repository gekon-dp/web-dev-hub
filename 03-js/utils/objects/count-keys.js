/** 

* Принимает объект и возвращает количество его свойств.
* @param {Object} object - Исходный объект для проверки
* @returns {number} Количество свойств (ключей) в объекте
*/
function countKeys(object) {
  let count = 0;

  // Проходим по каждому ключу и увеличиваем счетчик
  for (let key in object) {
    count++;
  }
  return count;
}
// --- Пример использования ---
const data = { a: 1, b: 2, c: 3, f: 78 };
console.log("Количество ключей:", countKeys(data)); // Выведет: 4

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. Способ Object.keys(object).length — это стандартный и самый быстрый способ узнать размер объекта в современном JS.
// 2. Если объект абсолютно пустой ({}), оба метода безопасно вернут цифру 0.
// 3. Помните, что цикл for...in может иногда перебирать свойства из прототипа объекта (если они были добавлены туда вручную), а Object.keys() собирает свойства строго самого объекта, что делает его более безопасным.
// 4. Современная альтернатива: const size = Object.keys(object).length;
