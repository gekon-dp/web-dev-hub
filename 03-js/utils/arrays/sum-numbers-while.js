/** 

* Принимает числовой массив и возвращает сумму его элементов, используя цикл while.
* @param {number[]} array - Исходный массив чисел
* @returns {number} Сумма всех элементов массива
*/
const sumNumbers = (array) => {
  let sum = 0;
  let i = 0;
  while (i < array.length) {
    sum += array[i];
    i++;
  }
  return sum;
};

// --- Пример использования ---
const numbers = [1000, 50, 120, 200];
console.log("Сумма (while):", sumNumbers(numbers)); // Выведет: 1370

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. Цикл while (Предусловие): Сначала проверяет условие, потом делает. Абсолютно безопасен для пустых массивов (условие i < 0 сразу вернет false).
// 2. Цикл do...while (Постусловие): Сначала делает один шаг, а потом проверяет условие. Если передать пустой массив , то на первом же шаге array вернет undefined, прибавится к sum, и итоговая сумма превратится в ошибку NaN.
// 3. Не забывайте вручную увеличивать индекс i++ внутри тела цикла while, иначе программа уйдет в бесконечный цикл и вкладка браузера или терминал намертво зависнут.
