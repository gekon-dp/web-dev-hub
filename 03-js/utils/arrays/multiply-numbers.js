/** 

* Принимает числовой массив и перемножает все его элементы между собой.
* @param {number[]} array - Исходный массив чисел
* @returns {number} Итоговое произведение всех элементов
*/
const multiplyNumbers = (array) => {
  let multiplyResult = 1;
  for (let key in array) {
    multiplyResult *= array[key];
  }
  return multiplyResult;
};

// --- Пример использования ---
const numbers = [9, 5, 12, 3];
console.log("Произведение элементов:", multiplyNumbers(numbers)); // Выведет: 1620

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. При подсчете суммы мы всегда пишем let sum = 0;, но при подсчете произведения — обязательно let product = 1;. Если случайно поставить 0, то результат всего умножения всегда будет равен нулю.
// 2. Если в функцию будет передан пустой массив [], цикл не выполнится ни разу, и функция вернет 1. В реальных задачах это поведение считается стандартным (нейтральный элемент умножения).
// 3. Метод .reduce() идеально справляется с этой задачей в современном JavaScript, как и в случае с суммированием.
