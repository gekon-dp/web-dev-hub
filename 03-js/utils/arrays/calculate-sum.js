/** 

* @file calculate-sum.js
* @description Подсчет суммы всех элементов числового массива.
* @task Task из учебного курса
*/

/** 

* Принимает массив чисел и возвращает их сумму.
* @param {number[]} array - Исходный массив чисел
* @returns {number} Сумма всех элементов
*/
const calculateSum = (array) => {
  let sum = 0;
  for (let key in array) {
    sum += array[key];
  }
  return sum;
};

// --- Пример использования ---
const numbers = [1, 2, 3, 4, 5];
console.log("Сумма элементов:", calculateSum(numbers)); // Выведет: 15

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. Переменная sum обязательно объявляется снаружи цикла и инициализируется нулем.
// 2. Вариант с for...in работает отлично, но важно помнить, что key в таком цикле — это индекс строки, а не число. Нам везет, что array[key] достает само число.
// 3. Метод .reduce() — это стандарт де-факто в JavaScript для подсчета сумм или агрегации данных. Стоит выучить его синтаксис, его очень часто просят написать на интервью.
