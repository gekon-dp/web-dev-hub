/** 

* @file double-numbers.js
* @description Функция удвоения элементов числового массива.
*/

/** 

* Принимает массив чисел и увеличивает каждый его элемент в два раза.
* @param {number[]} array - Исходный массив чисел
* @returns {number[]} Массив с удвоенными значениями
*/
const doubleNumbers = (array) => {
  for (let key in array) {
    // Умножаем текущее значение на 2 и записываем обратно
    array[key] = array[key] * 2;
  }
  return array;
};

// --- Пример использования ---
const numbers = [22, 43, 678, 21];
console.log("Исходный:", numbers);
console.log("Результат:", doubleNumbers(numbers));

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. Способ array[key] = array[key] * 2 изменяет оригинальный массив. Это называется мутацией данных.
// 2. Вместо * 2 можно использовать оператор присваивания с умножением: array[key] *= 2;.
// 3. Метод map() — это стандарт для таких задач в современном JS, так как он возвращает новый массив и сохраняет исходные данные в безопасности.
// 4. Современная альтернатива: const doubled = array.map(num => num * 2);
