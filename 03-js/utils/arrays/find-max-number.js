/** 

* Проверяет массив чисел и возвращает самое большое из них.
* @param {number[]} array - Исходный массив чисел
* @returns {number} Максимальное число в массиве
*/
const findMaxNumber = (array) => {
  // За стартовую точку берем первый элемент массива, а не 0
  let maxNumber = array;

  for (let key in array) {
    if (array[key] > maxNumber) {
      maxNumber = array[key]; // Обновляем максимум, если нашли число больше
    }
  }
  return maxNumber;
};
// --- Пример использования ---
const numbers = [32, 1, 45, 777, 312, 1234];
console.log("Максимальное число:", findMaxNumber(numbers)); // Выведет: 1234

// --- Важные нюансы для себя (Шпаргалка) ---
// 1. Нельзя инициализировать переменную максимума нулем (let maxNumber = 0), иначе функция отработает неверно на массиве, состоящем только из отрицательных чисел. Всегда безопаснее брать первый элемент — array.
// 2. Цикл for...in перебирает строковые ключи (индексы), поэтому для сравнения обязательно используем конструкцию array[key].
// 3. Конструкция Math.max(...array) с использованием оператора spread — это самый быстрый, надежный и красивый способ решения такой задачи в реальных проектах.
// 4. Современная альтернатива: const max = Math.max(...array);
